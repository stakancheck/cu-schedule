const WC_ABOUT: Record<string, string> = { "Туалет для маломобильных": "Отдельный туалет, куда можно заехать на коляске." };

export interface Info {
  cat: CatId;
  about: string | null;
  note: Note | null;   // подробности есть только у того, что заполнено в NOTES
}

const cache = new Map<string, Info>();
export function placeInfo(p: Place): Info {
  const hit = cache.get(p.key);
  if (hit) return hit;
  const label = p.label ?? (p.kind === "room" ? "" : p.title);
  let cat: CatId = "other", about: string | null = null;
  if (p.kind === "wc") { cat = "wc"; about = WC_ABOUT[p.title] || null; }
  else if (p.kind === "link") cat = "move";
  else if (p.kind === "entrance") { cat = "entry"; about = p.sub ? `Вход с улицы: ${p.sub}.` : null; }
  else if (p.kind === "room") cat = "study";
  else {
    const rule = RULES.find(([re, , , color]) => re.test(label) && (!color || color === p.color));
    if (rule) { cat = rule[1]; about = rule[2] || null; }
    else if (p.color === "staff") { cat = "staff"; about = "Офис сотрудников университета."; }
  }
  const note = (p.room && NOTES[p.room]) || NOTES[`${p.campus} ${p.floor} ${label}`] || NOTES[p.key] || null;
  const info: Info = { cat, about: note?.about || about, note };
  cache.set(p.key, info);
  return info;
}

// Текст для поиска: по нему находится и «кофемашина», если она записана в подробностях
export function infoText(p: Place) {
  const i = placeInfo(p);
  return [CATS[i.cat].name, i.about, i.note?.hours, i.note?.who, ...(i.note?.facts || [])].filter(Boolean).join(" ");
}
