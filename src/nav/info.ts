// В Дукате синим (у нас - цвет staff) отмечены места преподавателей и сотрудников: без приглашения туда не пройти
const STAFF_ZONE = "Служебная зона: свободно пройти не получится";
const KIND_CAT: Partial<Record<Place["kind"], CatId>> = { wc: "wc", link: "move", entrance: "entry", room: "study" };

export interface Info {
  cat: CatId;
  about: string | null;
  note: Note | null;   // нюансы: из правила по названию и из NOTES, null - нечего показать
  own: boolean;        // у места есть своя запись в NOTES
}

const cache = new Map<string, Info>();
export function placeInfo(p: Place): Info {
  const hit = cache.get(p.key);
  if (hit) return hit;
  const label = p.label ?? (p.kind === "room" ? "" : p.title);
  const rule = p.kind === "room" ? undefined
    : RULES.find((r) => r.re.test(label) && (!r.color || r.color === p.color) && (!r.campus || r.campus === p.campus));
  let cat: CatId = rule?.cat || KIND_CAT[p.kind] || "other";
  let about = rule?.about || (p.kind === "entrance" && p.sub ? `Вход с улицы: ${p.sub}.` : null);
  if (!rule && p.color === "staff") { cat = "staff"; about = "Офис сотрудников университета."; }
  const own = (p.room && NOTES[p.room]) || NOTES[`${p.campus} ${p.floor} ${label}`] || NOTES[p.key] || null;
  const facts = [...(own?.facts || []), ...(rule?.facts || [])];
  const who = own?.who || rule?.who || (p.campus === "DUCAT" && p.color === "staff" && cat !== "help" ? STAFF_ZONE : undefined);
  const hours = own?.hours || rule?.hours;
  const note: Note | null = facts.length || who || hours || own?.emoji || own?.brand || own?.links?.length || own?.keywords || own?.weekly ? { facts, who, hours, emoji: own?.emoji, brand: own?.brand, links: own?.links, keywords: own?.keywords, weekly: own?.weekly } : null;
  const info: Info = { cat, about: own?.about || about, note, own: !!own };
  cache.set(p.key, info);
  return info;
}

// Текст для поиска: по нему находится и «кофемашина», если она записана в подробностях.
// У аудитории с расписанием - только её запись в NOTES, без категории
export function infoText(p: Place) {
  const i = placeInfo(p);
  if (p.kind === "room") return i.own ? [i.about, ...(i.note?.facts || []), i.note?.keywords].filter(Boolean).join(" ") : "";
  return [CATS[i.cat].name, i.about, i.note?.hours, i.note?.who, ...(i.note?.facts || []), i.note?.keywords].filter(Boolean).join(" ");
}
